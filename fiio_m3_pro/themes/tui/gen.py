#!/usr/bin/env python3
"""Generate the "tui" Rockbox theme for the FiiO M3 Pro (340x800).

Everything is laid out on a 34x40 grid of 10x20 px cells (Terminus 20), so
box-drawing borders join up like a real TUI. Writes into ./.rockbox/:

  wps/tui.sbs        status bar + framed list panel
  wps/tui.wps        now playing: track / art+spectrum / playback / control
  themes/tui.cfg     colours, fonts, list geometry
  themes/tui.colours filetype colours for the file browser

Run:  python3 gen.py      (then validate with checkwps)
"""
import os
import random

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, ".rockbox")

COLS, ROWS = 34, 40
CW, CH = 10, 20

# Tokyo Night-ish palette
BG      = "0D1117"
FG      = "C0CAF5"
DIM     = "565F89"
BLUE    = "7AA2F7"
CYAN    = "7DCFFF"
PURPLE  = "BB9AF7"
GREEN   = "9ECE6A"
YELLOW  = "E0AF68"
ORANGE  = "FF9E64"
PINK    = "F7768E"
SEL     = "283457"   # selection highlight

# font slots: 1 = theme font (24 Terminus, lists), loaded below
F_BOLD, F_REG, F_BIG = 2, 3, 4
FONTS = "%%Fl(%d,20-Terminus-Bold.fnt)\n%%Fl(%d,20-Terminus.fnt)\n" % (F_BOLD, F_REG)


def vp(col, row, ncols, nrows, font, fg, lines, label=None, x_off=0, y_off=0,
       w=None, h=None):
    """A viewport on the cell grid, followed by its text lines."""
    x, y = col * CW + x_off, row * CH + y_off
    w = ncols * CW if w is None else w
    h = nrows * CH if h is None else h
    head = "%%Vl(%s,%d,%d,%d,%d,%s)" % (label, x, y, w, h, font) if label else \
           "%%V(%d,%d,%d,%d,%s)" % (x, y, w, h, font)
    return "%s%%Vf(%s)%%Vb(%s)\n%s\n" % (head, fg, BG, "\n".join(lines))


def panel(row0, row1, colour, title=None, title_fg=FG, gap_rows=()):
    """Rounded box from row0 to row1 (inclusive) across the full width,
    with an optional ┤ title ├ tab in the top border."""
    out = []
    inner = COLS - 2
    if title:
        tab = " %s " % title
        out.append(vp(0, row0, 3, 1, F_BOLD, colour, ["╭─┤"]))
        out.append(vp(3, row0, len(tab), 1, F_BOLD, title_fg, [tab]))
        rest = COLS - 3 - len(tab)
        out.append(vp(3 + len(tab), row0, rest, 1, F_BOLD, colour,
                      ["├" + "─" * (rest - 2) + "╮"]))
    else:
        out.append(vp(0, row0, COLS, 1, F_BOLD, colour, ["╭" + "─" * inner + "╮"]))
    # sides, split around divider rows
    r = row0 + 1
    while r < row1:
        start = r
        while r < row1 and r not in gap_rows:
            r += 1
        n = r - start
        if n:
            out.append(vp(0, start, 1, n, F_BOLD, colour, ["│"] * n))
            out.append(vp(COLS - 1, start, 1, n, F_BOLD, colour, ["│"] * n))
        if r in gap_rows:
            out.append(vp(0, r, COLS, 1, F_BOLD, colour, ["├" + "─" * inner + "┤"]))
            r += 1
    out.append(vp(0, row1, COLS, 1, F_BOLD, colour, ["╰" + "─" * inner + "╯"]))
    return "".join(out)


def status_panel():
    """Rows 0-2: framed status bar (60 px)."""
    s = panel(0, 2, BLUE)
    s += vp(2, 1, 10, 1, F_BOLD, GREEN,
            ["%?mp<■ stop|▶ play|‖ pause|▶▶ ffwd|◀◀ rwnd>"])
    s += vp(14, 1, 6, 1, F_BOLD, YELLOW, ["%?cc<%cH:%cM|--:-->"])
    s += vp(20, 1, 5, 1, F_BOLD, PURPLE, ["%ar%?bc<+|>%bl%%"])
    s += vp(26, 1, 1, 1, F_BOLD, DIM, ["│"])
    s += vp(27, 1, 6, 1, F_BOLD, CYAN, ["%ar%pv"])
    return s


# ---------------------------------------------------------------- sbs ----

def gen_sbs():
    s = "# Generated by gen.py -- edit that, not this file.\n"
    s += "# TUI status bar + framed list panel, 340x800 (FiiO M3 Pro)\n"
    s += FONTS
    # Lists/menus: inside the list panel, 16 px from the frame's left edge
    s += "%%Vi(-,%d,%d,%d,%d,1)\n" % (16, 4 * CH + 2, 340 - 16 - 14, 35 * CH - 4)
    s += status_panel()
    s += panel(3, 39, BLUE, "≡ rockbox", YELLOW)
    return s


# ---------------------------------------------------------------- wps ----

SPEC_COLS, SPEC_ROWS, SPEC_FRAMES, SPEC_DT = 15, 7, 16, 0.2
SPEC_BARS = 8   # bars at every other column
ROW_COLOURS = [GREEN, GREEN, YELLOW, YELLOW, ORANGE, PINK, PINK]  # bottom -> top
BLOCKS = " ▁▂▃▄▅▆▇█"


def spectrum_frames(seed=7):
    """Smooth pseudo-random column heights (in eighths of a cell)."""
    rnd = random.Random(seed)
    top = SPEC_ROWS * 8
    # bass-heavy envelope, like a real spectrum
    shape = [0.95 - 0.6 * i / (SPEC_BARS - 1) for i in range(SPEC_BARS)]
    h = [top * 0.3] * SPEC_BARS
    frames = []
    for _ in range(SPEC_FRAMES):
        h = [max(3, min(top, 0.35 * v + 0.65 * top * sh * rnd.uniform(0.15, 1.0)))
             for v, sh in zip(h, shape)]
        frames.append([int(v) for v in h])
    return frames


def spectrum_row_text(heights, row):
    out = []
    for v in heights:
        n = max(0, min(8, v - row * 8))
        out.append(BLOCKS[n] + " ")
    return "".join(out)[:SPEC_COLS]


def button(col, row, colour, label):
    w = 10
    pad = w - 2 - len(label)
    mid = "│" + " " * (pad // 2) + label + " " * (pad - pad // 2) + "│"
    return vp(col, row, w, 3, F_BOLD, colour,
              ["╭" + "─" * (w - 2) + "╮", mid, "╰" + "─" * (w - 2) + "╯"])


def field(row, label, colour, text, font=F_REG):
    return vp(2, row, 7, 1, F_BOLD, PURPLE, [label]) + \
           vp(10, row, 23, 1, font, colour, ["%s" % text])


def gen_wps():
    s = "# Generated by gen.py -- edit that, not this file.\n"
    s += "# TUI now playing, 340x800 (FiiO M3 Pro)\n%wd\n"
    s += FONTS + "%%Fl(%d,32-Terminus-Bold.fnt)\n" % F_BIG

    # which optional viewports are visible
    s += "%?C<%Vd(art)|%Vd(noart)>\n"
    s += "%?mp<%Vd(spec_off)|%Vd(spec_on)|%Vd(spec_off)|%Vd(spec_on)|%Vd(spec_on)>\n"
    s += "%?mp<%Vd(dot_off)|%Vd(dot_on)|%Vd(dot_off)|%Vd(dot_on)|%Vd(dot_on)>\n"

    # touch regions over the control buttons (absolute coordinates)
    s += "%V(0,0,340,800,-)\n"
    acts = [["prev", "play", "next"], ["voldown", "menu", "volup"]]
    for r, row in enumerate(acts):
        for c, act in enumerate(row):
            s += "%%T(%d,%d,100,60,%s)" % ((1 + 11 * c) * CW, (33 + 3 * r) * CH, act)
        s += "\n"

    # ---- status (rows 0-2)
    s += status_panel()

    # ---- track panel (rows 3-14), divider at row 10
    s += panel(3, 14, CYAN, "♪ now playing  ", YELLOW, gap_rows=(10,))
    dot_col = 3 + len(" ♪ now playing  ") - 1
    # pulsing dot next to the panel title while playing
    s += vp(dot_col, 3, 1, 1, F_BOLD, GREEN,
            [";".join("%%t(0.3)%s" % c for c in ("∙", "•", "●", "•"))], label="dot_on")
    s += vp(dot_col, 3, 1, 1, F_BOLD, DIM, ["∙"], label="dot_off")
    s += field(4, "artist", FG, "%s%?ia<%ia|%?iA<%iA|%?d(2)<%d(2)|---->>>")
    s += field(5, "album", FG, "%s%?id<%id|%?d(1)<%d(1)|---->>")
    s += field(6, "date", FG, "%?iy<%iy|----> · %?ig<%ig|---->")
    s += vp(2, 7, 31, 3, F_BIG, CYAN, ["%s%?it<%it|%fn>"], y_off=10, h=40)
    s += field(11, "codec", GREEN, "%fc %fkkHz %fbkbps")
    s += field(12, "next", ORANGE, "%s%?It<%It|%?Fn<%Fn|---->>")
    s += field(13, "queue", FG,
               "%pp/%pe  shf:%?ps<on|off>  rep:%?mm<off|all|one|shf|a-b>")

    # ---- art + spectrum panel (rows 15-24)
    s += panel(15, 24, PURPLE, "◆ art · spectrum", YELLOW)
    s += "%%Vl(art,%d,%d,160,160,-)\n%%Cl(0,0,160,160,c,c)\n%%Cd\n" % (1 * CW + 5, 16 * CH)
    s += vp(2, 19, 15, 1, F_BOLD, DIM, ["%ac[ no art ]"], label="noart")
    s += vp(2, 20, 15, 1, F_REG, DIM, ["%ac♪ ♪ ♪"], label="noart")
    frames = spectrum_frames()
    for row in range(SPEC_ROWS):            # row 0 = bottom
        grid_row = 16 + (SPEC_ROWS - 1 - row)
        line = ";".join("%%t(%.1f)%s" % (SPEC_DT, spectrum_row_text(f, row))
                        for f in frames)
        s += vp(18, grid_row, SPEC_COLS, 1, F_BOLD, ROW_COLOURS[row], [line],
                label="spec_on")
        idle = "▁ " * SPEC_BARS if row == 0 else ""
        s += vp(18, grid_row, SPEC_COLS, 1, F_BOLD, DIM, [idle[:SPEC_COLS]], label="spec_off")
    s += vp(18, 23, SPEC_COLS, 1, F_BOLD, DIM, ["%ac≈ live ≈"])

    # ---- playback panel (rows 25-31)
    s += panel(25, 31, GREEN, "▶ playback", YELLOW)
    s += vp(2, 26, 1, 1, F_BOLD, DIM, ["["]) + vp(31, 26, 1, 1, F_BOLD, DIM, ["]"])
    s += vp(3, 26, 28, 1, "-", GREEN, ["%pb(0,4,280,12,noborder)"])
    s += vp(2, 27, 9, 1, F_BOLD, GREEN, ["%pc"])
    s += vp(12, 27, 10, 1, F_BOLD, ORANGE, ["%ac-%pr"])
    s += vp(23, 27, 9, 1, F_BOLD, CYAN, ["%ar%pt"])
    s += vp(2, 28, 4, 1, F_BOLD, PURPLE, ["vol"])
    s += vp(7, 28, 25, 1, "-", PURPLE, ["%pv(0,6,250,8,noborder)"])
    s += vp(2, 29, 4, 1, F_BOLD, PURPLE, ["vu L"])
    s += vp(7, 29, 25, 1, "-", GREEN, ["%pL(0,5,250,10,noborder)"])
    s += vp(2, 30, 4, 1, F_BOLD, PURPLE, ["vu R"])
    s += vp(7, 30, 25, 1, "-", GREEN, ["%pR(0,5,250,10,noborder)"])

    # ---- control panel (rows 32-39)
    s += panel(32, 39, YELLOW, "■ control", YELLOW)
    s += button(1, 33, CYAN, "◀◀ prev")
    s += button(12, 33, CYAN, "▶‖ play")
    s += button(23, 33, CYAN, "next ▶▶")
    s += button(1, 36, PURPLE, "▼ vol-")
    s += button(12, 36, YELLOW, "≡ menu")
    s += button(23, 36, PURPLE, "▲ vol+")
    return s


# ---------------------------------------------------------------- cfg ----

def gen_cfg():
    return "\n".join([
        "# Generated by gen.py -- TUI theme for the FiiO M3 Pro (340x800)",
        "wps: /.rockbox/wps/tui.wps",
        "sbs: /.rockbox/wps/tui.sbs",
        "fms: -",
        "wrs: -",
        "backdrop: -",
        "font: /.rockbox/fonts/24-Terminus.fnt",
        "foreground color: " + FG,
        "background color: " + BG,
        "selector type: bar (color)",
        "line selector start color: " + SEL,
        "line selector end color: " + SEL,
        "line selector text color: " + FG,
        "list separator height: 1",
        "list separator color: 1F2335",
        "list padding: 40",
        "statusbar: top",
        "scrollbar: right",
        "scrollbar width: 4",
        "show icons: off",
        "iconset: -",
        "viewers iconset: -",
        "filetype colours: /.rockbox/themes/tui.colours",
        "ui viewport: -",
        "",
    ])


def gen_colours():
    music = ["mp3", "mp2", "mpa", "flac", "ogg", "oga", "opus", "m4a", "m4b", "mp4",
             "aac", "wav", "wv", "ape", "mpc", "aiff", "aif", "wma", "spx", "alac",
             "dsf", "dff", "sid", "mod", "nsf", "spc", "vgm", "vgz"]
    lines = ["folder: " + BLUE, "???: " + DIM]
    lines += ["%s: %s" % (e, GREEN) for e in music]
    lines += ["m3u: " + YELLOW, "m3u8: " + YELLOW, "pls: " + YELLOW,
              "cfg: " + PURPLE, "wps: " + PURPLE, "sbs: " + PURPLE,
              "txt: " + FG, "rock: " + PINK, "lua: " + PINK,
              "jpg: " + CYAN, "bmp: " + CYAN, "png: " + CYAN]
    return "\n".join(lines) + "\n"


def write(rel, text):
    p = os.path.join(OUT, rel)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote", rel, "(%d viewports)" % text.count("%V") if rel.endswith(("wps", "sbs")) else "")


if __name__ == "__main__":
    write("wps/tui.sbs", gen_sbs())
    write("wps/tui.wps", gen_wps())
    write("themes/tui.cfg", gen_cfg())
    write("themes/tui.colours", gen_colours())
